import type { Frame, StepAction, WorkflowStep } from './types.js';
import { AiError, parseJsonReply, type AskFn } from './ai.js';
import { uid } from './planner.js';
import { sliceBudget, type SubagentResult, type SubagentStatus, type SubagentTask } from './subagents.js';

/** Most moves a recorded pack captures. */
export const PACK_MOVE_LIMIT = 5;
/** Background test results kept per pack, newest first. */
export const PACK_TEST_LIMIT = 10;
/** The input kinds a pack records: click, navigate (a recorded cursor move), type, key, scroll and drag. */
export const PACK_MOVES: ReadonlySet<StepAction> = new Set<StepAction>(['click', 'move', 'type', 'key', 'scroll', 'drag']);

/** A recorded pack (capped at PACK_MOVE_LIMIT moves) or a workflow combined from packs (uncapped). */
export type PackKind = 'recorded' | 'combined';
/** Where a pack's goal came from: the user's input, the AI, an edit in the goal bar; null while it has none. */
export type GoalSource = 'input' | 'ai' | 'user' | null;

/** One background test of a pack. */
export interface PackTestResult {
  id: string;
  time: number;
  status: SubagentStatus;
  message: string;
  /** Ran disarmed: verified on the live screen, nothing sent. */
  dry: boolean;
}

/** A named set of recorded moves with its goal and its background test log. */
export interface WorkflowPack {
  id: string;
  name: string;
  kind: PackKind;
  goal: string;
  goalSource: GoalSource;
  steps: WorkflowStep[];
  tests: PackTestResult[];
  savedAt: number;
}

/** Steps picked for a cross-run: whole packs and single steps. */
export interface PackSelection {
  packIds: string[];
  stepIds: string[];
}

/** The step of a perform-similar run that did not complete. */
export interface FailingStep {
  /** 1-based position in the plan. */
  index: number;
  total: number;
  name: string;
  action: StepAction;
  target: string;
  x: number;
  y: number;
  reason: string;
}

/** The outcome of "perform similar action": complete, or exactly where it is incomplete. */
export type SimilarReport = { complete: true; message: string } | { complete: false; message: string; failing: FailingStep | null };

/** One planned step as it ran on the live screen. */
export interface StepRun {
  ok: boolean;
  message: string;
  target?: { x: number; y: number };
}

const pct = (v: number) => `${(v * 100).toFixed(1)}%`;
const fresh = (s: WorkflowStep): WorkflowStep => ({ ...s, status: 'pending' });

/**
 * The goal stated in the user's input: trimmed, without a "goal:" label or a lead-in such as
 * "I want to" / "please", without trailing punctuation, first letter capitalised. Empty when none.
 */
export function extractGoal(input: string): string {
  let goal = input.trim().replace(/^(goal|objective|task)\s*[:\-–]\s*/i, '');
  const lead = /^(i want to|i'd like to|i would like to|i need to|help me|can you|could you|please)\s+/i;
  while (lead.test(goal)) goal = goal.replace(lead, '');
  goal = goal.replace(/[\s.!?]+$/, '').trim();
  return goal.replace(/^\w/, (c) => c.toUpperCase());
}

/** A new empty pack whose goal is extracted from `input`. */
export function newPack(name: string, input: string, now = Date.now()): WorkflowPack {
  const goal = extractGoal(input);
  return { id: uid('pack'), name: name.trim() || 'Pack', kind: 'recorded', goal, goalSource: goal ? 'input' : null, steps: [], tests: [], savedAt: now };
}

/** True when a recorded pack holds its PACK_MOVE_LIMIT moves. */
export const isFull = (pack: WorkflowPack) => pack.kind === 'recorded' && pack.steps.length >= PACK_MOVE_LIMIT;

/** Records one move into a pack; refused for a non-move action or a full pack. */
export function addMove(pack: WorkflowPack, step: WorkflowStep, now = Date.now()): { pack: WorkflowPack; added: boolean; reason?: string } {
  if (!PACK_MOVES.has(step.action)) return { pack, added: false, reason: `"${step.action}" is not a pack move` };
  if (isFull(pack)) return { pack, added: false, reason: `"${pack.name}" already holds ${PACK_MOVE_LIMIT} moves` };
  return { pack: { ...pack, steps: [...pack.steps, fresh(step)], savedAt: now }, added: true };
}

/** The pack with a goal typed in its goal bar (user-edited) or generated by the AI. */
export const withGoal = (pack: WorkflowPack, goal: string, source: Exclude<GoalSource, null>, now = Date.now()): WorkflowPack => ({ ...pack, goal: goal.trim(), goalSource: goal.trim() ? source : null, savedAt: now });

/**
 * One combined workflow of the chosen packs (in list order) with copies of their steps; the
 * sources stay unchanged. Its goal joins the parts' goals when every part has one.
 */
export function combinePacks(packs: WorkflowPack[], ids: string[], now = Date.now()): WorkflowPack | { error: string } {
  const chosen = packs.filter((p) => ids.includes(p.id));
  if (chosen.length < 2) return { error: 'Select at least two packs to combine' };
  const goal = chosen.every((p) => p.goal) ? chosen.map((p) => p.goal).join(' then ') : '';
  const steps = chosen.flatMap((p) => p.steps.map((s) => ({ ...fresh(s), id: uid('step') })));
  return { id: uid('pack'), name: chosen.map((p) => p.name).join(' + '), kind: 'combined', goal, goalSource: goal ? 'input' : null, steps, tests: [], savedAt: now };
}

/** Moves one step to the end of another pack; refused when the target is a full recorded pack. */
export function moveStep(packs: WorkflowPack[], stepId: string, toPackId: string, now = Date.now()): { packs: WorkflowPack[] } | { error: string } {
  const from = packs.find((p) => p.steps.some((s) => s.id === stepId));
  const to = packs.find((p) => p.id === toPackId);
  if (!from || !to) return { error: 'That step or pack no longer exists' };
  if (from.id === to.id) return { packs };
  if (isFull(to)) return { error: `"${to.name}" already holds ${PACK_MOVE_LIMIT} moves` };
  const step = from.steps.find((s) => s.id === stepId)!;
  return {
    packs: packs.map((p) => {
      if (p.id === from.id) return { ...p, steps: p.steps.filter((s) => s.id !== stepId), savedAt: now };
      if (p.id === to.id) return { ...p, steps: [...p.steps, step], savedAt: now };
      return p;
    }),
  };
}

/** The steps a cross-run runs: packs in list order, steps in pack order, each step once. */
export function crossRunSelection(packs: WorkflowPack[], sel: PackSelection): WorkflowStep[] {
  const seen = new Set<string>();
  return packs
    .flatMap((p) => (sel.packIds.includes(p.id) ? p.steps : p.steps.filter((s) => sel.stepIds.includes(s.id))))
    .filter((s) => !seen.has(s.id) && !!seen.add(s.id))
    .map(fresh);
}

/** One step as a line: action, target, typed text and where it was recorded. */
export const stepLine = (s: WorkflowStep) => `${s.action} "${s.target ?? s.name}"${s.text ? ` with "${s.text}"` : ''} at (${pct(s.x)}, ${pct(s.y)})`;

const GOAL_SYSTEM = 'You are Droid Assist. Given the recorded steps of a workflow and the current screen, state the goal they achieve as one short imperative sentence. Reply ONLY with JSON: {"goal":string}';

/** The AI's goal for a pack without one, from its steps and the live frame; AiError when the reply has none. */
export async function generateGoal(ask: AskFn, steps: WorkflowStep[], frame: Frame | null): Promise<string> {
  const reply = await ask({ system: GOAL_SYSTEM, prompt: `Recorded steps:\n${steps.map((s, i) => `${i + 1}. ${stepLine(s)}`).join('\n')}`, frame, json: true });
  const goal = parseJsonReply(reply.content).goal;
  if (typeof goal !== 'string' || !goal.trim()) throw new AiError('AI returned no goal for this pack');
  return goal.trim();
}

/** The goal a perform-similar plan is made from: the selected steps as an example to adapt to the live screen. */
export const similarGoal = (steps: WorkflowStep[]) => `Perform an action similar to these recorded steps on the screen as it is now: ${steps.map(stepLine).join(' → ')}`;

/** The failing step of a plan: its position, what it does, where it aimed and why it failed. */
function failingStep(plan: WorkflowStep[], i: number, run: StepRun | undefined): FailingStep {
  const s = plan[i];
  const at = run?.target ?? { x: s.x, y: s.y };
  return { index: i + 1, total: plan.length, name: s.name, action: s.action, target: s.target ?? s.name, x: at.x, y: at.y, reason: run ? run.message : 'not run — the run stopped before it' };
}

/**
 * The report of a perform-similar run: complete only when the plan has steps and every one ran
 * ok; otherwise incomplete naming the planning failure or the first step that failed or never ran.
 */
export function similarReport(plan: WorkflowStep[], runs: StepRun[], dryRun: boolean, planError?: string): SimilarReport {
  if (planError) return { complete: false, message: `Incomplete — no plan: ${planError}`, failing: null };
  if (!plan.length) return { complete: false, message: 'Incomplete — the AI found no similar action on this screen', failing: null };
  const bad = plan.findIndex((_, i) => !runs[i]?.ok);
  if (bad < 0) return { complete: true, message: `Complete — ${plan.length} step(s) ${dryRun ? 'verified on the live screen (dry run)' : 'performed'}` };
  const f = failingStep(plan, bad, runs[bad]);
  return { complete: false, message: `Incomplete at step ${f.index}/${f.total} "${f.name}" — ${f.action} "${f.target}" at (${pct(f.x)}, ${pct(f.y)}): ${f.reason}`, failing: f };
}

/** One background test task per pack with steps, each with its slice of the action budget; the task id is the pack id. */
export function packTestTasks(packs: WorkflowPack[], totalBudget: number): SubagentTask[] {
  const testable = packs.filter((p) => p.steps.length);
  const budgets = sliceBudget(totalBudget, testable.length);
  return testable.map((p, i) => ({ id: p.id, index: i, kind: 'route', label: p.name, goal: p.goal || p.name, target: p.name, budget: budgets[i] }));
}

/** A subagent result as a pack test entry. */
export const packTestResult = (r: SubagentResult, now = Date.now()): PackTestResult => ({ id: uid('test'), time: now, status: r.status, message: r.message, dry: r.dry });

/** The pack with `result` first in its test log, keeping the newest PACK_TEST_LIMIT. */
export const appendTestResult = (pack: WorkflowPack, result: PackTestResult): WorkflowPack => ({ ...pack, tests: [result, ...pack.tests].slice(0, PACK_TEST_LIMIT) });
